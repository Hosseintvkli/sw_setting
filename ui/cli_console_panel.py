class CliCommandTextError(ValueError):
    pass


@dataclass(frozen=True)
class ParsedCliInvocation:
    original_text: str
    program: str
    arguments: list[str]
    command_name: str
    session_name: str | None


def parse_cli_invocation(command_text: str) -> ParsedCliInvocation:
    """Validate and split one GUI/script line without invoking a shell."""
    original = command_text.strip()
    if not original:
        raise CliCommandTextError("Command is empty.")

    try:
        tokens = [
            _remove_matching_outer_quotes(token)
            for token in shlex.split(original, posix=False)
        ]
    except ValueError as exc:
        raise CliCommandTextError(f"Invalid command quoting: {exc}") from exc
    if len(tokens) < 3:
        raise CliCommandTextError(
            "Expected a complete command such as: python cli.py --session gui status"
        )

    displayed_program = tokens[0]
    executable_name = Path(displayed_program).name.lower()
    allowed_python_names = {
        "python",
        "python.exe",
        "python3",
        "python3.exe",
        "py",
        "py.exe",
        Path(sys.executable).name.lower(),
    }
    if executable_name not in allowed_python_names:
        raise CliCommandTextError("The command must start with python or py.")
    program = (
        displayed_program
        if Path(displayed_program).is_absolute()
        else sys.executable
    )

    cli_token = tokens[1]
    if Path(cli_token).name.lower() != "cli.py":
        raise CliCommandTextError("The Python script must be cli.py.")

    cli_arguments = tokens[2:]
    session_name: str | None = None
    command_name: str | None = None
    i = 0
    while i < len(cli_arguments):
        token = cli_arguments[i]
        if token == "--session":
            if i + 1 >= len(cli_arguments):
                raise CliCommandTextError("--session requires a name.")
            session_name = cli_arguments[i + 1]
            i += 2
            continue
        if token.startswith("--session="):
            session_name = token.split("=", 1)[1]
            i += 1
            continue
        if not token.startswith("-") and command_name is None:
            command_name = token
        i += 1

    if not command_name:
        raise CliCommandTextError("The cli.py command name is missing.")

    return ParsedCliInvocation(
        original_text=original,
        program=program,
        arguments=[cli_token, *cli_arguments],
        command_name=command_name,
        session_name=session_name,
    )


def _remove_matching_outer_quotes(token: str) -> str:
    if len(token) >= 2 and token[0] == token[-1] and token[0] in ("'", '"'):
        return token[1:-1]
    return token


def build_copyable_cli_command(arguments_after_cli: list[str]) -> str:
    """Create the exact command text generated by GUI controls on Windows."""
    return subprocess.list2cmdline(["python", "cli.py", *arguments_after_cli])


def script_command_lines(script_text: str) -> list[str]:
    """Return executable CLI lines; only blank lines and # comments are skipped."""
    commands: list[str] = []
    for line_number, raw_line in enumerate(script_text.splitlines(), start=1):
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        try:
            parsed = parse_cli_invocation(line)
        except CliCommandTextError as exc:
            raise CliCommandTextError(f"Script line {line_number}: {exc}") from exc
        if parsed.command_name == "serve-http":
            raise CliCommandTextError(
                f"Script line {line_number}: serve-http is a long-running server "
                "command and cannot be part of a sequential script."
            )
        commands.append(line)
    return commands


CompletionCallback = Callable[[dict[str, Any] | None, int], None]


class CliHistoryLineEdit(QLineEdit):
    """Command input with terminal-like Up/Down history navigation."""

    def __init__(self, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        self._history: list[str] = []
        self._history_index = 0
        self._draft_text = ""

    def remember(self, command_text: str) -> None:
        command = command_text.strip()
        if command and (not self._history or self._history[-1] != command):
            self._history.append(command)
        self._history_index = len(self._history)
        self._draft_text = ""

    def keyPressEvent(self, event: QKeyEvent) -> None:  # noqa: N802
        if event.key() == Qt.Key.Key_Up and self._history:
            if self._history_index == len(self._history):
                self._draft_text = self.text()
            self._history_index = max(0, self._history_index - 1)
            self.setText(self._history[self._history_index])
            return
        if event.key() == Qt.Key.Key_Down and self._history:
            self._history_index = min(len(self._history), self._history_index + 1)
            if self._history_index == len(self._history):
                self.setText(self._draft_text)
            else:
                self.setText(self._history[self._history_index])
            return
        super().keyPressEvent(event)


