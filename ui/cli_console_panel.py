    def _session_name(self) -> str:
        return self.session_name_line_edit.text().strip()

    @property
    def is_command_running(self) -> bool:
        return self._active_process is not None

    def build_session_command(self, command_name: str, *arguments: str) -> str:
        return self._session_command(command_name, *arguments)

    def execute_session_command(
        self,
        command_name: str,
        arguments: list[str] | None = None,
        completion_callback: CompletionCallback | None = None,
    ) -> bool:
        try:
            command = self._session_command(command_name, *(arguments or []))
        except CliCommandTextError as exc:
            QMessageBox.warning(self, "Session", str(exc))
            return False
        return self.execute_command(command, completion_callback)

    def request_session_cancel(self) -> bool:
        """Run the copyable CLI cancel command alongside the active command."""
        if self._cancel_process is not None:
            QMessageBox.information(
                self, "Cancel", "A cancellation request is already running."
            )
            return False
        try:
            command = self._session_command("cancel")
            parsed = parse_cli_invocation(command)
        except CliCommandTextError as exc:
            QMessageBox.warning(self, "Cancel", str(exc))
            return False

        history_item = QTreeWidgetItem(["Running", command, ""])
        self.command_history_tree.addTopLevelItem(history_item)
        self.command_history_tree.scrollToItem(history_item)
        self._append_output(f"> {command}\n")

        process = QProcess(self)
        process.setWorkingDirectory(str(self._project_root))
        output = {"stdout": "", "stderr": "", "finalized": False}

        def read_stdout() -> None:
            text = bytes(process.readAllStandardOutput()).decode(
                "utf-8", errors="replace"
            )
            output["stdout"] += text
            self._append_output(text)

        def read_stderr() -> None:
            text = bytes(process.readAllStandardError()).decode(
                "utf-8", errors="replace"
            )
            output["stderr"] += text
            self._append_output(text)

        def finalize(exit_code: int) -> None:
            if output["finalized"]:
                return
            output["finalized"] = True
            read_stdout()
            read_stderr()
            history_item.setText(0, "OK" if exit_code == 0 else "Failed")
            history_item.setText(2, str(exit_code))
            payload: dict[str, Any] | None = None
            try:
                decoded = json.loads(output["stdout"]) if output["stdout"].strip() else None
                if isinstance(decoded, dict):
                    payload = decoded
            except json.JSONDecodeError:
                pass
            self._cancel_process = None
            self._append_output(f"[exit code {exit_code}]\n\n")
            self.command_completed.emit(command, exit_code, payload)

        def process_error(error) -> None:
            message = f"Cancel process error: {process.errorString()}\n"
            output["stderr"] += message
            self._append_output(message)
            if error == QProcess.ProcessError.FailedToStart:
                finalize(127)

        process.readyReadStandardOutput.connect(read_stdout)
        process.readyReadStandardError.connect(read_stderr)
        process.finished.connect(lambda exit_code, _status: finalize(exit_code))
        process.errorOccurred.connect(process_error)
        self._cancel_process = process
        process.start(parsed.program, parsed.arguments)
        return True

    def _session_command(self, command_name: str, *arguments: str) -> str:
        name = self._session_name()
        if not name:
            raise CliCommandTextError("Enter a session name first.")
        return build_copyable_cli_command(
            ["--session", name, command_name, *arguments]
        )

    def _auto_start_default_session(self) -> None:
        self._ensure_http_server(self._attach_or_create_named_session)

    def _http_server_is_healthy(self) -> bool:
        try:
            with urlopen("http://127.0.0.1:8000/health", timeout=0.25) as response:
                return 200 <= int(response.status) < 300
        except (OSError, URLError):
            return False

    def _ensure_http_server(self, callback: Callable[[], None]) -> None:
        if self._http_server_is_healthy():
            callback()
            return
        self._server_ready_callbacks.append(callback)
        if self._server_process is not None:
            return

        command = build_copyable_cli_command(
            ["serve-http", "--host", "127.0.0.1", "--port", "8000"]
        )
        parsed = parse_cli_invocation(command)
        self._append_output(f"> {command}\n")
        self._server_history_item = QTreeWidgetItem(["Starting", command, ""])
        self.command_history_tree.addTopLevelItem(self._server_history_item)

        process = QProcess(self)
        process.setWorkingDirectory(str(self._project_root))
        process.readyReadStandardOutput.connect(self._read_server_stdout)
        process.readyReadStandardError.connect(self._read_server_stderr)
        process.finished.connect(self._server_process_finished)
        process.errorOccurred.connect(self._server_process_error)
        self._server_process = process
        process.start(parsed.program, parsed.arguments)
        self._server_health_attempts = 0
        QTimer.singleShot(150, self._poll_server_health)

    def _poll_server_health(self) -> None:
        if self._http_server_is_healthy():
            if self._server_history_item is not None:
                self._server_history_item.setText(0, "Running")
            callbacks = self._server_ready_callbacks
            self._server_ready_callbacks = []
            for callback in callbacks:
                callback()
            return
        self._server_health_attempts += 1
        if self._server_health_attempts >= 40:
            self._server_ready_callbacks = []
            self.session_status_label.setText("HTTP server failed to start")
            QMessageBox.critical(
                self,
                "HTTP server",
                "serve-http did not become ready on 127.0.0.1:8000.",
            )
            return
        QTimer.singleShot(150, self._poll_server_health)

    def _read_server_stdout(self) -> None:
        if self._server_process is not None:
            text = bytes(self._server_process.readAllStandardOutput()).decode(
                "utf-8", errors="replace"
            )
            self._append_output(text)

    def _read_server_stderr(self) -> None:
        if self._server_process is not None:
            text = bytes(self._server_process.readAllStandardError()).decode(
                "utf-8", errors="replace"
            )
            self._append_output(text)

    def _server_process_finished(self, exit_code: int, _status) -> None:
        if self._server_history_item is not None:
            self._server_history_item.setText(0, "Stopped")
            self._server_history_item.setText(2, str(exit_code))
        self._server_process = None

    def _server_process_error(self, _error) -> None:
        if self._server_process is not None:
            self._append_output(
                f"serve-http process error: {self._server_process.errorString()}\n"
            )

    def _attach_or_create_named_session(self) -> None:
        session_name = self._session_name()
        try:
            stored_state = read_http_session_state(
                self._project_root, session_name=session_name
            )
        except HttpSessionClientError as exc:
            self.session_status_label.setText(str(exc))
            return
        if stored_state is None:
            self.create_named_session()
            return
        if not self._stored_server_session_is_live(stored_state):
            self.create_named_session()
            return
        self._check_named_session(auto_create=True)

    def _stored_server_session_is_live(self, stored_state: dict[str, Any]) -> bool:
        base_url = str(stored_state.get("base_url") or "").rstrip("/")
        expected_id = str(stored_state.get("session_id") or "")
        if not base_url or not expected_id:
            return False
        try:
            with urlopen(f"{base_url}/sessions", timeout=0.5) as response:
                payload = json.loads(response.read().decode("utf-8"))
        except (OSError, URLError, json.JSONDecodeError):
            return False
        sessions = payload.get("sessions") if isinstance(payload, dict) else None
        if not isinstance(sessions, list):
            return False
        return any(
            isinstance(item, dict) and str(item.get("session_id") or "") == expected_id
            for item in sessions
        )

    def _check_named_session(self, *, auto_create: bool) -> None:
        session_name = self._session_name()
        try:
            command = self._session_command("status")
        except CliCommandTextError as exc:
            self.session_status_label.setText(str(exc))
            return

        def after_status(payload: dict[str, Any] | None, exit_code: int) -> None:
            if exit_code == 0:
                self.session_status_label.setText(f"Attached: {session_name}")
                self.session_ready.emit(session_name)
                return
            error = str((payload or {}).get("error") or "")
            if auto_create and (
                "No active HTTP session" in error or "HTTP 404" in error
            ):
                self.create_named_session()
            else:
                self.session_status_label.setText("Attach failed")

        self.execute_command(command, after_status)

    def create_named_session(self) -> None:
        session_name = self._session_name()
        try:
            command = self._session_command("serve")
        except CliCommandTextError as exc:
            QMessageBox.warning(self, "Session", str(exc))
            return

        def after_create(_payload: dict[str, Any] | None, exit_code: int) -> None:
            if exit_code == 0:
                self._owned_session_names.add(session_name)
                self.session_status_label.setText(f"Created: {session_name}")
                self.session_ready.emit(session_name)
            else:
                self.session_status_label.setText("Create failed")

        def run_create() -> None:
            self.execute_command(
                command,
                after_create,
            )

        self._ensure_http_server(run_create)

    def attach_named_session(self) -> None:
        self._ensure_http_server(
            lambda: self._check_named_session(auto_create=False)
        )

    def stop_named_session(self) -> None:
        session_name = self._session_name()
        try:
            command = self._session_command("serve-stop")
        except CliCommandTextError as exc:
            QMessageBox.warning(self, "Session", str(exc))
            return
        def after_stop(_payload: dict[str, Any] | None, exit_code: int) -> None:
            if exit_code == 0:
                self._owned_session_names.discard(session_name)
                self.session_status_label.setText("Stopped")
            else:
                self.session_status_label.setText("Stop failed")

        self.execute_command(command, after_stop)

    def run_command_from_input(self) -> None:
        self.execute_command(self.command_line_edit.text())

    def execute_command(
        self,
        command_text: str,
        completion_callback: CompletionCallback | None = None,
    ) -> bool:
        if self._active_process is not None:
            QMessageBox.information(
                self, "CLI busy", "Wait for the current command to finish."
            )
            return False
        try:
            parsed = parse_cli_invocation(command_text)
        except CliCommandTextError as exc:
            QMessageBox.warning(self, "Invalid CLI command", str(exc))
            return False

        self.command_line_edit.setText(parsed.original_text)
        self.command_line_edit.remember(parsed.original_text)
        self._active_command_text = parsed.original_text
        self._active_stdout = ""
        self._active_stderr = ""
        self._active_callback = completion_callback
        self._active_history_item = QTreeWidgetItem(
            ["Running", parsed.original_text, ""]
        )
        self.command_history_tree.addTopLevelItem(self._active_history_item)
        self.command_history_tree.scrollToItem(self._active_history_item)
        self._append_output(f"> {parsed.original_text}\n")

        process = QProcess(self)
        process.setWorkingDirectory(str(self._project_root))
        process.readyReadStandardOutput.connect(self._read_command_stdout)
        process.readyReadStandardError.connect(self._read_command_stderr)
        process.finished.connect(self._command_process_finished)
        process.errorOccurred.connect(self._command_process_error)
        self._active_process = process
        self._set_command_controls_busy(True)
        process.start(parsed.program, parsed.arguments)
        return True

    def _read_command_stdout(self) -> None:
        if self._active_process is None:
            return
        text = bytes(self._active_process.readAllStandardOutput()).decode(
            "utf-8", errors="replace"
        )
        self._active_stdout += text
        self._append_output(text)

    def _read_command_stderr(self) -> None:
        if self._active_process is None:
            return
        text = bytes(self._active_process.readAllStandardError()).decode(
            "utf-8", errors="replace"
        )
        self._active_stderr += text
        self._append_output(text)

    def _command_process_error(self, error) -> None:
        if self._active_process is not None:
            message = f"Process error: {self._active_process.errorString()}\n"
            self._active_stderr += message
            self._append_output(message)
            if error == QProcess.ProcessError.FailedToStart:
                self._finalize_active_process(127)

    def _command_process_finished(self, exit_code: int, _status) -> None:
        self._finalize_active_process(exit_code)

    def _finalize_active_process(self, exit_code: int) -> None:
        if self._active_process is None:
            return
        self._read_command_stdout()
        self._read_command_stderr()
        if self._active_history_item is not None:
            self._active_history_item.setText(0, "OK" if exit_code == 0 else "Failed")
            self._active_history_item.setText(2, str(exit_code))

        payload: dict[str, Any] | None = None
        try:
            decoded = json.loads(self._active_stdout) if self._active_stdout.strip() else None
            if isinstance(decoded, dict):
                payload = decoded
        except json.JSONDecodeError:
            pass

        command_text = self._active_command_text
        callback = self._active_callback
        self._active_process = None
        self._active_history_item = None
        self._active_callback = None
        self._set_command_controls_busy(False)
        self._append_output(f"[exit code {exit_code}]\n\n")
        self.command_completed.emit(command_text, exit_code, payload)
        if callback is not None:
            callback(payload, exit_code)

        if self._script_queue:
            if exit_code != 0 and self._script_stop_on_error:
                remaining = len(self._script_queue)
                self._script_queue.clear()
                self._append_output(
                    f"Script stopped after failure; {remaining} command(s) skipped.\n"
                )
            else:
                next_command = self._script_queue.popleft()
                QTimer.singleShot(0, lambda: self.execute_command(next_command))

    def _set_command_controls_busy(self, busy: bool) -> None:
        self.run_button.setEnabled(not busy)
        self.run_script_button.setEnabled(not busy)
        self.create_session_button.setEnabled(not busy)
        self.attach_session_button.setEnabled(not busy)
        self.stop_session_button.setEnabled(not busy)
        self.busy_changed.emit(busy)

    def copy_current_command(self) -> None:
        selected_item = self.command_history_tree.currentItem()
        text = (
            selected_item.text(1).strip()
            if selected_item is not None
            else self.command_line_edit.text().strip()
        )
        if text:
            QGuiApplication.clipboard().setText(text)

    def _copy_history_item_to_input(
        self, item: QTreeWidgetItem, _column: int
    ) -> None:
        command = item.text(1)
        self.command_line_edit.setText(command)
        QGuiApplication.clipboard().setText(command)

    def load_script(self) -> None:
        path, _ = QFileDialog.getOpenFileName(
            self,
            "Load CLI script",
            str(self._project_root),
            "CLI scripts (*.txt *.swscript);;All files (*.*)",
        )
        if not path:
            return
        try:
            text = Path(path).read_text(encoding="utf-8")
            script_command_lines(text)
        except (OSError, UnicodeError, CliCommandTextError) as exc:
            QMessageBox.warning(self, "Load script", str(exc))
            return
        self.script_editor.setPlainText(text)

    def save_script(self) -> None:
        try:
            script_command_lines(self.script_editor.toPlainText())
        except CliCommandTextError as exc:
            QMessageBox.warning(self, "Save script", str(exc))
            return
        path, _ = QFileDialog.getSaveFileName(
            self,
            "Save CLI script",
            str(self._project_root / "commands.swscript"),
            "CLI scripts (*.swscript);;Text files (*.txt);;All files (*.*)",
        )
        if not path:
            return
        try:
            Path(path).write_text(self.script_editor.toPlainText(), encoding="utf-8")
        except OSError as exc:
            QMessageBox.critical(self, "Save script", str(exc))

    def run_script(self) -> None:
        if self._active_process is not None:
            QMessageBox.information(self, "CLI busy", "A command is already running.")
            return
        try:
            commands = script_command_lines(self.script_editor.toPlainText())
        except CliCommandTextError as exc:
            QMessageBox.warning(self, "Invalid script", str(exc))
            return
        if not commands:
            QMessageBox.information(self, "CLI script", "The script has no commands.")
            return
        self._script_queue = deque(commands[1:])
        self.execute_command(commands[0])

    def stop_script(self) -> None:
        skipped = len(self._script_queue)
        self._script_queue.clear()
        self._append_output(
            f"Script will stop after the current command; {skipped} queued command(s) removed.\n"
        )

    def _append_output(self, text: str) -> None:
        if not text:
            return
        cursor = self.output_text_edit.textCursor()
        cursor.movePosition(cursor.MoveOperation.End)
        cursor.insertText(text)
        self.output_text_edit.setTextCursor(cursor)
        self.output_text_edit.ensureCursorVisible()

    def shutdown(self) -> None:
        self._script_queue.clear()
        if self._cancel_process is not None:
            self._cancel_process.terminate()
            self._cancel_process.waitForFinished(1000)
            if self._cancel_process is not None:
                self._cancel_process.kill()
        if self._active_process is not None:
            self._active_process.terminate()
            self._active_process.waitForFinished(1500)
            if self._active_process is not None:
                self._active_process.kill()
        if self._http_server_is_healthy():
            for session_name in sorted(self._owned_session_names):
                command = build_copyable_cli_command(
                    ["--session", session_name, "serve-stop"]
                )
                parsed = parse_cli_invocation(command)
                close_process = QProcess()
                close_process.setWorkingDirectory(str(self._project_root))
                close_process.start(parsed.program, parsed.arguments)
                close_process.waitForFinished(3000)
        self._owned_session_names.clear()
        if self._server_process is not None:
            self._server_process.terminate()
            self._server_process.waitForFinished(2000)
            if self._server_process is not None:
                self._server_process.kill()
